// GetMsgName 返回消息名称，去掉 _id 后缀
func GetMsgName(msgID uint16) string {
	name, ok := pb.EGameMsgID_name[int32(msgID)]
	if !ok {
		return "Unknown"
	}
	// 去掉 _id 后缀
	if len(name) > 3 && name[len(name)-3:] == "_id" {
		return name[:len(name)-3]
	}
	return name
}

// NewMessage 根据 MsgID 创建消息实例（副本）
func NewMessage(msgID uint16) (proto.Message, bool) {
	tmpl, ok := msgRegistry[msgID]
	if !ok {
		return nil, false
	}
	return proto.Clone(tmpl), true
}
